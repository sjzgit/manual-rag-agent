-- V011__prompt_context_to_user_message
-- 说明：上下文缓存优化——回答生成的参考切片从 system prompt 移到末条 user 消息：
--       1. 之前检索切片 format 进 answer_system，每次调用 system 内容都变化，
--          无法命中 LLM 提供方的 prompt 缓存；
--       2. 调整后 system 与历史消息保持固定，仅末条 user 消息（用户输入 +
--          【参考切片】一节）随请求变化，前缀稳定可命中缓存；
--       3. 本脚本把库中 answer_system 覆盖为无 {context} 占位符的新版代码默认值
--          （应用侧 chat_service 已同步改为把上下文拼进 user 消息，旧模板若不更新，
--          字面 "{context}" 会残留在 system 中）。
--       注意：answer_system 若已在管理端自定义，本更新会覆盖自定义内容，
--       如需保留请先备份 prompt_templates 中该行再执行。
-- 应用范围：已上线环境增量执行（顺序执行：V001 -> ... -> V011）。
-- ============================================================================

USE manual_rag;

-- 回答生成提示词更新为固定版本（切片位置说明改为用户消息末尾）
UPDATE prompt_templates SET content = '你是企业操作手册智能助手。检索到的参考切片附在用户消息末尾的【参考切片】一节，你的回答必须严格基于该内容，遵守以下规则：

1. 只根据【参考切片】回答，不要编造手册中不存在的功能、按钮或步骤。
2. 如果参考切片不足以回答用户问题，明确回复"手册中未找到相关内容"，并可建议用户补充功能模块名称。
3. 回答条理清晰，操作步骤用有序列表呈现；涉及界面按钮时使用「」标注。
4. 切片中的图片链接（形如 ![](/api/images/...)，表示该处有操作截图）是图文混排的重要内容：回答时必须在对应的操作步骤位置**原样保留**这些图片链接，不得删除、不得重排、不得改写成文字说明，以便用户直接看到图文信息。
5. 回答末尾必须附来源，格式（每个来源一行）：
来源：文档名 > 路径
' WHERE `key` = 'answer_system';
